/*
TPS A7 document storage DDL draft, SQL Server 2019-compatible.
Target: newly prepared local [TPS].[dbo] only. DO NOT run against MES_LITE.
This file was prepared, not executed. Root must verify server/database and approve execution.
No source RPS_ table or row is changed. No seed business data is inserted.
Actor keys nvarchar(100) are a proposed bounded contract, not verified MES key lengths.
Initial application storage is BLOB; schema reserves OBJECT without enabling an object store.
*/
USE [TPS];
SET NOCOUNT ON;
SET XACT_ABORT ON;

IF DB_NAME() <> N'TPS'
    THROW 51000, 'Target database must be TPS.', 1;
IF @@TRANCOUNT <> 0
    THROW 51001, 'Run this script without an ambient transaction.', 1;
IF NOT EXISTS (SELECT 1 FROM sys.fn_helpcollations() WHERE name = N'Korean_100_CS_AI_KS_WS_SC_UTF8')
    THROW 51002, 'Required case-sensitive UTF8 collation is unavailable.', 1;
IF SCHEMA_ID(N'dbo') IS NULL
    THROW 51003, 'Expected dbo schema is unavailable.', 1;

BEGIN TRY
    BEGIN TRANSACTION;

    -- Never silently reuse, delete or replace an existing object.
    IF EXISTS (
        SELECT 1
        FROM sys.objects AS o
        INNER JOIN sys.schemas AS s ON s.schema_id = o.schema_id
        WHERE s.name = N'dbo' AND o.name IN (
            N'TPS_DOC_TEMPLATE', N'TPS_DOC_REVISION', N'TPS_DOC_ACTIVATION',
            N'TPS_DOC_ASSET', N'TPS_DOC_REVISION_ASSET', N'TPS_DOC_IMPORT', N'TPS_DOC_REQUEST'
        )
    )
        THROW 51004, 'An A7 target object already exists; inspect instead of overwriting.', 1;

    CREATE TABLE dbo.TPS_DOC_REQUEST (
        SITE_ID varchar(40) COLLATE Korean_100_CS_AI_KS_WS_SC_UTF8 NOT NULL,
        RECEIPT_ID uniqueidentifier NOT NULL,
        ACTOR_ID nvarchar(100) COLLATE Korean_100_CS_AI_KS_WS_SC_UTF8 NOT NULL,
        OPERATION varchar(32) COLLATE Latin1_General_100_BIN2 NOT NULL,
        SCOPE_KIND varchar(16) COLLATE Latin1_General_100_BIN2 NOT NULL,
        SCOPE_ID uniqueidentifier NOT NULL,
        REQUEST_KEY varchar(64) COLLATE Latin1_General_100_BIN2 NOT NULL,
        FINGERPRINT binary(32) NOT NULL,
        FINGERPRINT_VERSION varchar(40) COLLATE Latin1_General_100_BIN2 NOT NULL,
        STATUS varchar(20) COLLATE Latin1_General_100_BIN2 NOT NULL,
        RESULT_JSON nvarchar(max) NULL,
        CREATED_AT datetime2(3) NOT NULL CONSTRAINT DF_TPS_DOC_REQUEST_CREATED DEFAULT (SYSUTCDATETIME()),
        COMPLETED_AT datetime2(3) NULL,
        CONSTRAINT PK_TPS_DOC_REQUEST PRIMARY KEY CLUSTERED (SITE_ID, RECEIPT_ID),
        CONSTRAINT UQ_TPS_DOC_REQUEST_KEY UNIQUE NONCLUSTERED
            (SITE_ID, ACTOR_ID, OPERATION, SCOPE_KIND, SCOPE_ID, REQUEST_KEY),
        CONSTRAINT CK_TPS_DOC_REQUEST_SCOPE CHECK (SCOPE_KIND IN ('CLIENT_DRAFT', 'TEMPLATE')),
        CONSTRAINT CK_TPS_DOC_REQUEST_TEXT CHECK
            (DATALENGTH(SITE_ID) > 0 AND DATALENGTH(ACTOR_ID) > 0 AND DATALENGTH(OPERATION) > 0
             AND DATALENGTH(REQUEST_KEY) > 0 AND DATALENGTH(FINGERPRINT_VERSION) > 0 AND DATALENGTH(STATUS) > 0),
        CONSTRAINT CK_TPS_DOC_REQUEST_JSON CHECK (RESULT_JSON IS NULL OR ISJSON(RESULT_JSON) = 1),
        CONSTRAINT CK_TPS_DOC_REQUEST_TIME CHECK (COMPLETED_AT IS NULL OR COMPLETED_AT >= CREATED_AT)
    );

    CREATE TABLE dbo.TPS_DOC_TEMPLATE (
        SITE_ID varchar(40) COLLATE Korean_100_CS_AI_KS_WS_SC_UTF8 NOT NULL,
        TEMPLATE_ID uniqueidentifier NOT NULL,
        OWNER_MODULE varchar(3) COLLATE Latin1_General_100_BIN2 NOT NULL,
        NAME nvarchar(200) NOT NULL,
        HEAD_REVISION_ID uniqueidentifier NULL,
        HEAD_TOKEN bigint NOT NULL CONSTRAINT DF_TPS_DOC_TEMPLATE_HEAD_TOKEN DEFAULT (0),
        ACTIVE_REVISION_ID uniqueidentifier NULL,
        ACTIVE_TOKEN bigint NOT NULL CONSTRAINT DF_TPS_DOC_TEMPLATE_ACTIVE_TOKEN DEFAULT (0),
        ENABLED bit NOT NULL CONSTRAINT DF_TPS_DOC_TEMPLATE_ENABLED DEFAULT (1),
        CREATED_AT datetime2(3) NOT NULL CONSTRAINT DF_TPS_DOC_TEMPLATE_CREATED DEFAULT (SYSUTCDATETIME()),
        CREATED_BY nvarchar(100) COLLATE Korean_100_CS_AI_KS_WS_SC_UTF8 NOT NULL,
        CONSTRAINT PK_TPS_DOC_TEMPLATE PRIMARY KEY CLUSTERED (SITE_ID, TEMPLATE_ID),
        CONSTRAINT UQ_TPS_DOC_TEMPLATE_OWNER UNIQUE NONCLUSTERED (SITE_ID, TEMPLATE_ID, OWNER_MODULE),
        CONSTRAINT CK_TPS_DOC_TEMPLATE_OWNER CHECK (OWNER_MODULE IN ('RPS', 'LPS')),
        CONSTRAINT CK_TPS_DOC_TEMPLATE_TOKENS CHECK (HEAD_TOKEN >= 0 AND ACTIVE_TOKEN >= 0),
        CONSTRAINT CK_TPS_DOC_TEMPLATE_TEXT CHECK
            (DATALENGTH(SITE_ID) > 0 AND DATALENGTH(NAME) > 0 AND DATALENGTH(CREATED_BY) > 0)
    );

    CREATE TABLE dbo.TPS_DOC_REVISION (
        SITE_ID varchar(40) COLLATE Korean_100_CS_AI_KS_WS_SC_UTF8 NOT NULL,
        TEMPLATE_ID uniqueidentifier NOT NULL,
        REVISION_ID uniqueidentifier NOT NULL,
        REVISION_NO bigint NOT NULL,
        PARENT_REVISION_ID uniqueidentifier NULL,
        SCHEMA_VERSION varchar(40) COLLATE Latin1_General_100_BIN2 NOT NULL,
        BODY_JSON nvarchar(max) NOT NULL,
        BODY_HASH binary(32) NOT NULL,
        HASH_VERSION varchar(40) COLLATE Latin1_General_100_BIN2 NOT NULL,
        VALIDATION_STATE varchar(24) COLLATE Latin1_General_100_BIN2 NOT NULL,
        DIAGNOSTICS_JSON nvarchar(max) NOT NULL,
        CREATED_AT datetime2(3) NOT NULL CONSTRAINT DF_TPS_DOC_REVISION_CREATED DEFAULT (SYSUTCDATETIME()),
        CREATED_BY nvarchar(100) COLLATE Korean_100_CS_AI_KS_WS_SC_UTF8 NOT NULL,
        REASON nvarchar(1000) NULL,
        CONSTRAINT PK_TPS_DOC_REVISION PRIMARY KEY CLUSTERED (SITE_ID, TEMPLATE_ID, REVISION_ID),
        CONSTRAINT UQ_TPS_DOC_REVISION_NO UNIQUE NONCLUSTERED (SITE_ID, TEMPLATE_ID, REVISION_NO),
        CONSTRAINT FK_TPS_DOC_REVISION_TEMPLATE FOREIGN KEY (SITE_ID, TEMPLATE_ID)
            REFERENCES dbo.TPS_DOC_TEMPLATE (SITE_ID, TEMPLATE_ID),
        CONSTRAINT FK_TPS_DOC_REVISION_PARENT FOREIGN KEY (SITE_ID, TEMPLATE_ID, PARENT_REVISION_ID)
            REFERENCES dbo.TPS_DOC_REVISION (SITE_ID, TEMPLATE_ID, REVISION_ID),
        CONSTRAINT CK_TPS_DOC_REVISION_NO CHECK (REVISION_NO > 0),
        CONSTRAINT CK_TPS_DOC_REVISION_PARENT CHECK (PARENT_REVISION_ID IS NULL OR PARENT_REVISION_ID <> REVISION_ID),
        CONSTRAINT CK_TPS_DOC_REVISION_JSON CHECK (ISJSON(BODY_JSON) = 1 AND ISJSON(DIAGNOSTICS_JSON) = 1),
        CONSTRAINT CK_TPS_DOC_REVISION_TEXT CHECK
            (DATALENGTH(SCHEMA_VERSION) > 0 AND DATALENGTH(HASH_VERSION) > 0
             AND DATALENGTH(VALIDATION_STATE) > 0 AND DATALENGTH(CREATED_BY) > 0)
    );

    -- A new template is inserted with NULL head inside the save transaction, then
    -- its first revision and head pointer are inserted/updated before save succeeds.
    ALTER TABLE dbo.TPS_DOC_TEMPLATE WITH CHECK
        ADD CONSTRAINT FK_TPS_DOC_TEMPLATE_HEAD FOREIGN KEY (SITE_ID, TEMPLATE_ID, HEAD_REVISION_ID)
            REFERENCES dbo.TPS_DOC_REVISION (SITE_ID, TEMPLATE_ID, REVISION_ID);
    ALTER TABLE dbo.TPS_DOC_TEMPLATE WITH CHECK
        ADD CONSTRAINT FK_TPS_DOC_TEMPLATE_ACTIVE FOREIGN KEY (SITE_ID, TEMPLATE_ID, ACTIVE_REVISION_ID)
            REFERENCES dbo.TPS_DOC_REVISION (SITE_ID, TEMPLATE_ID, REVISION_ID);

    CREATE TABLE dbo.TPS_DOC_ASSET (
        SITE_ID varchar(40) COLLATE Korean_100_CS_AI_KS_WS_SC_UTF8 NOT NULL,
        ASSET_ID uniqueidentifier NOT NULL,
        CONTENT_HASH binary(32) NOT NULL,
        MEDIA_TYPE varchar(100) COLLATE Latin1_General_100_BIN2 NOT NULL,
        BYTE_LENGTH bigint NOT NULL,
        STATE varchar(20) COLLATE Latin1_General_100_BIN2 NOT NULL,
        STORAGE_KIND varchar(12) COLLATE Latin1_General_100_BIN2 NOT NULL,
        BLOB_DATA varbinary(max) NULL,
        STORAGE_KEY nvarchar(512) COLLATE Latin1_General_100_BIN2 NULL,
        STATE_TOKEN bigint NOT NULL CONSTRAINT DF_TPS_DOC_ASSET_TOKEN DEFAULT (0),
        CREATED_AT datetime2(3) NOT NULL CONSTRAINT DF_TPS_DOC_ASSET_CREATED DEFAULT (SYSUTCDATETIME()),
        CREATED_BY nvarchar(100) COLLATE Korean_100_CS_AI_KS_WS_SC_UTF8 NOT NULL,
        CONSTRAINT PK_TPS_DOC_ASSET PRIMARY KEY CLUSTERED (SITE_ID, ASSET_ID),
        CONSTRAINT UQ_TPS_DOC_ASSET_HASH_REF UNIQUE NONCLUSTERED (SITE_ID, ASSET_ID, CONTENT_HASH),
        CONSTRAINT CK_TPS_DOC_ASSET_STATE CHECK (STATE IN ('STAGED', 'READY', 'DELETING')),
        CONSTRAINT CK_TPS_DOC_ASSET_SIZE CHECK (BYTE_LENGTH >= 0 AND STATE_TOKEN >= 0),
        CONSTRAINT CK_TPS_DOC_ASSET_LOCATION CHECK (
            (STORAGE_KIND = 'BLOB' AND BLOB_DATA IS NOT NULL AND STORAGE_KEY IS NULL AND DATALENGTH(BLOB_DATA) = BYTE_LENGTH)
            OR (STORAGE_KIND = 'OBJECT' AND BLOB_DATA IS NULL AND STORAGE_KEY IS NOT NULL AND DATALENGTH(STORAGE_KEY) > 0)
        ),
        CONSTRAINT CK_TPS_DOC_ASSET_TEXT CHECK
            (DATALENGTH(SITE_ID) > 0 AND DATALENGTH(MEDIA_TYPE) > 0 AND DATALENGTH(CREATED_BY) > 0)
    );

    CREATE TABLE dbo.TPS_DOC_REVISION_ASSET (
        SITE_ID varchar(40) COLLATE Korean_100_CS_AI_KS_WS_SC_UTF8 NOT NULL,
        TEMPLATE_ID uniqueidentifier NOT NULL,
        REVISION_ID uniqueidentifier NOT NULL,
        LOCAL_ASSET_ID nvarchar(128) COLLATE Latin1_General_100_BIN2 NOT NULL,
        ASSET_ID uniqueidentifier NOT NULL,
        EXPECTED_HASH binary(32) NOT NULL,
        ROLE varchar(32) COLLATE Latin1_General_100_BIN2 NOT NULL,
        CONSTRAINT PK_TPS_DOC_REVISION_ASSET PRIMARY KEY CLUSTERED (SITE_ID, TEMPLATE_ID, REVISION_ID, LOCAL_ASSET_ID),
        CONSTRAINT FK_TPS_DOC_REVISION_ASSET_REVISION FOREIGN KEY (SITE_ID, TEMPLATE_ID, REVISION_ID)
            REFERENCES dbo.TPS_DOC_REVISION (SITE_ID, TEMPLATE_ID, REVISION_ID),
        CONSTRAINT FK_TPS_DOC_REVISION_ASSET_FILE FOREIGN KEY (SITE_ID, ASSET_ID, EXPECTED_HASH)
            REFERENCES dbo.TPS_DOC_ASSET (SITE_ID, ASSET_ID, CONTENT_HASH),
        CONSTRAINT CK_TPS_DOC_REVISION_ASSET_TEXT CHECK (DATALENGTH(LOCAL_ASSET_ID) > 0 AND DATALENGTH(ROLE) > 0)
    );

    CREATE TABLE dbo.TPS_DOC_IMPORT (
        SITE_ID varchar(40) COLLATE Korean_100_CS_AI_KS_WS_SC_UTF8 NOT NULL,
        IMPORT_ID uniqueidentifier NOT NULL,
        ORIGIN_KIND varchar(20) COLLATE Latin1_General_100_BIN2 NOT NULL,
        SOURCE_SYSTEM nvarchar(100) NOT NULL,
        SOURCE_KEY_JSON nvarchar(max) NOT NULL,
        SOURCE_BUNDLE_ASSET_ID uniqueidentifier NOT NULL,
        SOURCE_RAW_HASH binary(32) NOT NULL,
        BUNDLE_HASH binary(32) NOT NULL,
        MANIFEST_HASH binary(32) NOT NULL,
        CONVERTER_VERSION varchar(80) COLLATE Latin1_General_100_BIN2 NOT NULL,
        OPTIONS_JSON nvarchar(max) NOT NULL,
        MAPPING_JSON nvarchar(max) NOT NULL,
        DIAGNOSTICS_JSON nvarchar(max) NOT NULL,
        RESULT_TEMPLATE_ID uniqueidentifier NULL,
        RESULT_REVISION_ID uniqueidentifier NULL,
        OBSERVED_AT datetime2(3) NOT NULL,
        CREATED_AT datetime2(3) NOT NULL CONSTRAINT DF_TPS_DOC_IMPORT_CREATED DEFAULT (SYSUTCDATETIME()),
        CONSTRAINT PK_TPS_DOC_IMPORT PRIMARY KEY CLUSTERED (SITE_ID, IMPORT_ID),
        CONSTRAINT FK_TPS_DOC_IMPORT_BUNDLE FOREIGN KEY (SITE_ID, SOURCE_BUNDLE_ASSET_ID, BUNDLE_HASH)
            REFERENCES dbo.TPS_DOC_ASSET (SITE_ID, ASSET_ID, CONTENT_HASH),
        CONSTRAINT FK_TPS_DOC_IMPORT_RESULT FOREIGN KEY (SITE_ID, RESULT_TEMPLATE_ID, RESULT_REVISION_ID)
            REFERENCES dbo.TPS_DOC_REVISION (SITE_ID, TEMPLATE_ID, REVISION_ID),
        CONSTRAINT CK_TPS_DOC_IMPORT_RESULT_PAIR CHECK (
            (RESULT_TEMPLATE_ID IS NULL AND RESULT_REVISION_ID IS NULL)
            OR (RESULT_TEMPLATE_ID IS NOT NULL AND RESULT_REVISION_ID IS NOT NULL)
        ),
        CONSTRAINT CK_TPS_DOC_IMPORT_JSON CHECK (
            ISJSON(SOURCE_KEY_JSON) = 1 AND ISJSON(OPTIONS_JSON) = 1
            AND ISJSON(MAPPING_JSON) = 1 AND ISJSON(DIAGNOSTICS_JSON) = 1
        ),
        CONSTRAINT CK_TPS_DOC_IMPORT_TEXT CHECK
            (DATALENGTH(ORIGIN_KIND) > 0 AND DATALENGTH(SOURCE_SYSTEM) > 0 AND DATALENGTH(CONVERTER_VERSION) > 0)
    );

    CREATE TABLE dbo.TPS_DOC_ACTIVATION (
        SITE_ID varchar(40) COLLATE Korean_100_CS_AI_KS_WS_SC_UTF8 NOT NULL,
        ACTIVATION_ID uniqueidentifier NOT NULL,
        TEMPLATE_ID uniqueidentifier NOT NULL,
        OLD_REVISION_ID uniqueidentifier NULL,
        NEW_REVISION_ID uniqueidentifier NOT NULL,
        OLD_ACTIVE_TOKEN bigint NOT NULL,
        NEW_ACTIVE_TOKEN bigint NOT NULL,
        REQUEST_RECEIPT_ID uniqueidentifier NOT NULL,
        OCCURRED_AT datetime2(3) NOT NULL CONSTRAINT DF_TPS_DOC_ACTIVATION_TIME DEFAULT (SYSUTCDATETIME()),
        ACTOR_ID nvarchar(100) COLLATE Korean_100_CS_AI_KS_WS_SC_UTF8 NOT NULL,
        REASON nvarchar(1000) NULL,
        CONSTRAINT PK_TPS_DOC_ACTIVATION PRIMARY KEY CLUSTERED (SITE_ID, ACTIVATION_ID),
        CONSTRAINT UQ_TPS_DOC_ACTIVATION_TOKEN UNIQUE NONCLUSTERED (SITE_ID, TEMPLATE_ID, NEW_ACTIVE_TOKEN),
        CONSTRAINT UQ_TPS_DOC_ACTIVATION_REQUEST UNIQUE NONCLUSTERED (SITE_ID, REQUEST_RECEIPT_ID),
        CONSTRAINT FK_TPS_DOC_ACTIVATION_OLD FOREIGN KEY (SITE_ID, TEMPLATE_ID, OLD_REVISION_ID)
            REFERENCES dbo.TPS_DOC_REVISION (SITE_ID, TEMPLATE_ID, REVISION_ID),
        CONSTRAINT FK_TPS_DOC_ACTIVATION_NEW FOREIGN KEY (SITE_ID, TEMPLATE_ID, NEW_REVISION_ID)
            REFERENCES dbo.TPS_DOC_REVISION (SITE_ID, TEMPLATE_ID, REVISION_ID),
        CONSTRAINT FK_TPS_DOC_ACTIVATION_REQUEST FOREIGN KEY (SITE_ID, REQUEST_RECEIPT_ID)
            REFERENCES dbo.TPS_DOC_REQUEST (SITE_ID, RECEIPT_ID),
        CONSTRAINT CK_TPS_DOC_ACTIVATION_TOKENS CHECK (
            OLD_ACTIVE_TOKEN >= 0 AND NEW_ACTIVE_TOKEN > 0
            AND CONVERT(decimal(20,0), NEW_ACTIVE_TOKEN) = CONVERT(decimal(20,0), OLD_ACTIVE_TOKEN) + 1
        ),
        CONSTRAINT CK_TPS_DOC_ACTIVATION_ACTOR CHECK (DATALENGTH(ACTOR_ID) > 0)
    );

    -- A small initial set supports immutable-file references and template audit lookup.
    CREATE INDEX IX_TPS_DOC_REVISION_PARENT
        ON dbo.TPS_DOC_REVISION (SITE_ID, TEMPLATE_ID, PARENT_REVISION_ID);
    CREATE INDEX IX_TPS_DOC_REVISION_ASSET_FILE
        ON dbo.TPS_DOC_REVISION_ASSET (SITE_ID, ASSET_ID);
    CREATE INDEX IX_TPS_DOC_IMPORT_BUNDLE
        ON dbo.TPS_DOC_IMPORT (SITE_ID, SOURCE_BUNDLE_ASSET_ID);
    CREATE INDEX IX_TPS_DOC_IMPORT_RESULT
        ON dbo.TPS_DOC_IMPORT (SITE_ID, RESULT_TEMPLATE_ID, RESULT_REVISION_ID);

    COMMIT TRANSACTION;
END TRY
BEGIN CATCH
    IF XACT_STATE() <> 0 ROLLBACK TRANSACTION;
    THROW;
END CATCH;

-- Re-run protection intentionally fails rather than treating an existing schema as equivalent.
SELECT N'A7_CREATED' AS result, COUNT_BIG(*) AS a7_table_count
FROM sys.tables AS t
INNER JOIN sys.schemas AS s ON s.schema_id = t.schema_id
WHERE s.name = N'dbo' AND t.name IN (
    N'TPS_DOC_TEMPLATE', N'TPS_DOC_REVISION', N'TPS_DOC_ACTIVATION',
    N'TPS_DOC_ASSET', N'TPS_DOC_REVISION_ASSET', N'TPS_DOC_IMPORT', N'TPS_DOC_REQUEST'
);
